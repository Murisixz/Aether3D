"""Showcase D -- a camera through a Stage 16 world: a crane-and-push over an alpine valley.

The Stage 16 alpine valley (eroded ranges, a river, a lake, forests, a village, golden-hour
sun, sky with glows, height fog) is generated by Aether3D exactly as in its own showcase.
Through it, a camera rises from the meadow below the village over its rooftops while
turning from the houses to the lake and the massif beyond, in one eased move
(``follow_path`` with ``sine`` in-out timing), its path a smooth spline (Catmull-Rom:
continuous velocity) through five control points over the terrain (``height``
queries; raised until the whole move keeps 12 m of clearance, measured at 240 samples a
second) while it looks at a target travelling from the village to the peaks, held off-centre by
the look-at constraint's composition (``screen``: the left third), and its lens zooms
from 28 to 40 mm (``camera.fov`` keyed from those focal lengths). The move is measured by
``motion_report`` (jitter, drift, steps; the subject in frame) and the path's lowest
clearance above the terrain is reported. It writes:

* ``hero.png`` (1920x1080, GPU path tracer: Sobol', Blackman-Harris, adaptive, denoised;
  the Stage 16 showcases' neutral tonemap) and ``hero_preview.png``;
* ``sheet.png`` -- six moments of the move;
* a 6-second 60 fps flight (GPU rasterizer with cascaded sun shadows):
  ``flight_1080p.mp4``, ``flight_master.mkv`` and the committed ``flight_preview.mp4``;
* ``report.json``.

    .venv/bin/python examples/film_d_world.py [--quick] [--no-video] [--part all|hero|video]
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from film_common import (  # noqa: E402
    OUT,
    arguments,
    film_options,
    preview,
    sequence,
    sheet,
    still,
    write_report,
)
from worlds_alpine_valley import LAKE, build  # noqa: E402
from worlds_common import exposure  # noqa: E402

DURATION = 6.0
LENS = (28.0, 40.0)
CLEARANCE = 12.0  # metres above the terrain, everywhere along the path


def lowest_clearance(scene, valley, cam) -> float:
    """The lowest the eye comes over the terrain along the move (240 samples a second)."""
    a = scene.animation
    lowest = np.inf
    for t in np.linspace(0.0, DURATION, int(DURATION * 240) + 1).tolist():
        p = a._posed_worlds(t)[cam.id][:3, 3]
        lowest = min(lowest, float(p[2] - valley.height(float(p[0]), float(p[1]))))
    return lowest


def camera_rig(scene, valley, info) -> dict:
    """The eye's path (a smooth spline through five control points over the ground), the
    aim's, the lens, the composition; the control points are raised until the whole move
    keeps the clearance."""
    a = scene.animation
    vx, vy = info["settlements"]["settlements"][0]["at"]
    lx, ly, _lr = LAKE
    # (from the Stage 16 showcase's village viewpoint, evenly spaced about 40 m apart:
    # rising 80 m over the rooftops in six seconds)
    raw = [(vx - 62, vy - 88, 34), (vx - 40, vy - 55, 48), (vx - 18, vy - 22, 66),
           (vx + 4, vy + 11, 88), (vx + 26, vy + 44, 114)]  # fmt: skip
    aims = [(vx, vy, valley.height(vx, vy) + 4.0),
            (vx + 150.0, vy + 200.0, valley.height(vx, vy) + 8.0),
            (lx, ly, valley.height(lx, ly) + 10.0)]  # fmt: skip
    raise_by, tries = 0.0, []
    for _attempt in range(6):
        eyes = [[float(x), float(y), valley.height(x, y) + up + raise_by] for x, y, up in raw]
        with scene.transaction("Flight camera"):
            cam = scene.add_camera("Flight", position=tuple(eyes[0]), look_at=aims[0],
                                   focal_length=LENS[0], far=40000.0)  # fmt: skip
            aim = scene.add_object("Flight aim", position=aims[0])
            a.add_path("Flight path", eyes)
            a.add_path("Flight aim path", [list(map(float, p)) for p in aims])
            a.follow_path(cam, "Flight path", start=0.0, end=DURATION, easing="sine",
                          follow=False)  # fmt: skip
            a.follow_path(aim, "Flight aim path", start=0.0, end=DURATION, easing="sine",
                          follow=False)  # fmt: skip
            aim_at = {"name": "Aim", "type": "look_at", "target": {"object": aim.id},
                      "screen": [-0.33, -0.05]}  # fmt: skip
            a.add_constraint(cam, aim_at)
            fovs = []
            for mm in LENS:  # (the focal length is the sensor's and the field of view's)
                lens = cam.camera.copy()
                lens.configure(focal_length=mm)
                fovs.append(lens.fov)
            a.set_channel(cam, "camera.fov", [(0.0, fovs[0]), (DURATION, fovs[1])],
                          interpolation="sine", ease="in_out")  # fmt: skip
            a.set_timeline(fps=60, start=0.0, end=DURATION)
        lowest = lowest_clearance(scene, valley, cam)
        tries.append({"raised_m": raise_by, "lowest_clearance_m": round(lowest, 3)})
        if lowest >= CLEARANCE:
            break
        scene.history.undo()  # (one step: the whole rig) -- raise the points and try again
        raise_by += CLEARANCE - lowest + 2.0
    scene.active_camera = cam
    return {"control_points": len(raw), "aims": len(aims), "lens_mm": list(LENS),
            "lowest_clearance_m": round(lowest, 3), "required_clearance_m": CLEARANCE,
            "attempts": tries}  # fmt: skip


def raster_options(quick: bool) -> dict:
    # (the Stage 16 golden-hour preset's exposure and tonemap: daylight keeps its colour)
    ev = exposure("golden")
    if quick:
        return {"backend": "cpu", "width": 192, "height": 108, "tonemap": "neutral", "exposure": ev}
    shadows = {"cascades": 4, "distance": 6000.0, "map_size": 4096}
    return {"backend": "gpu", "width": 1920, "height": 1080, "tonemap": "neutral",
            "exposure": ev, "samples": 4, "shadows": shadows}  # fmt: skip


def main() -> dict:
    args = arguments(__doc__)
    out = args.out or OUT / "d_world"
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    scene, valley, info = build()
    report: dict = {"showcase": "D camera through a world", "quick": args.quick,
                    "world": {"preset": "alpine_valley", "seed": valley.definition.get("seed"),
                              "regional": info["regional"]},
                    "build_seconds": round(time.perf_counter() - t0, 1)}  # fmt: skip
    report["camera"] = camera_rig(scene, valley, info)
    quality = scene.animation.motion_report(["Flight"], subject="Flight aim", rate=120)
    report["camera_quality"] = [f["code"] for f in quality.get("findings", [])]
    options = raster_options(args.quick)
    if args.part in ("all", "hero"):
        opts = {**film_options(args.quick, samples=256, adaptive=0.02,
                               exposure=exposure("golden")), "tonemap": "neutral"}  # fmt: skip
        hero = still(scene, out / "hero.png", opts, time=3.4)
        report["hero"] = {k: v for k, v in hero.items() if k != "image"}
        report["hero_preview"] = preview(hero["image"], out / "hero_preview.png")
        moments = (0.0, 1.2, 2.4, 3.6, 4.8, 6.0)
        small = {**options, "width": options["width"] // 3, "height": options["height"] // 3}
        images = [scene.render(**small, time=t).image for t in moments]
        report["sheet"] = sheet(images, [f"t = {t:.1f} s" for t in moments], out / "sheet.png")
    if not args.no_video and args.part in ("all", "video"):
        end = 2 / 60 if args.quick else DURATION
        report["flight"] = sequence(scene, out, "flight", start=0.0, end=end, options=options,
                                    quick=args.quick)  # fmt: skip
    report["seconds"] = round(time.perf_counter() - t0, 1)
    write_report(out / "report.json", report)
    return report


if __name__ == "__main__":
    data = main()
    print(f"D world: {data['seconds']} s, camera {data['camera']}, {data['camera_quality']}")
